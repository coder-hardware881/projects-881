class turtle{
    constructor(c,v,c_side,ctx){
        this.c=c;
        this.v=v;
        this.c_side=c_side;
        this.ctx=ctx;
        this.a=0;
    }
    move(s){
        this.ctx.moveTo(...this.c);
        this.c=[this.v[0]*s+this.c[0],-this.v[1]*s+this.c[1]];
        this.ctx.lineTo(...this.c);
    }
    moveup(s){
        this.c=[this.v[0]*s+this.c[0],-this.v[1]*s+this.c[1]];
    }
    turn_abs(angle){
        this.a=angle;
        this.v=[(Math.cos(angle*Math.PI/180).toFixed(2))*1,(Math.sin(angle*Math.PI/180).toFixed(2))*1];
    }
    turn(angle){
        this.a+=angle;
        this.v=[(Math.cos(this.a*Math.PI/180).toFixed(2))*1,(Math.sin(this.a*Math.PI/180).toFixed(2))*1];
    }
    clear(){
        this.ctx.clearRect(0,0,this.c_side,this.c_side);
        this.ctx.beginPath();
    }
}